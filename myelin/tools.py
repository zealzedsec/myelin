"""Brain operations exposed to agents — one implementation behind both the MCP
server (Claude Code) and the API agent (`myelin ask`), so the two cannot drift.

Write operations here only ever *stage* proposals. Nothing an agent calls can
edit a note directly; accepting a proposal is a separate, human-side action.
Note content returned to an agent is wrapped and labelled as data, because a
vault note may itself contain text that reads like instructions.
"""
from __future__ import annotations

import json
import re
from typing import Any

from . import proposals as P
from .brain import Brain
from .learning import record_access, record_feedback, resolve_note
from .recall import RecallEngine

MAX_NOTE_CHARS = 12000


class BrainTools:
    def __init__(self, brain: Brain, engine: RecallEngine, source: str = "agent", session: str | None = None):
        self.brain = brain
        self.engine = engine
        self.source = source
        self.session = session

    def recall(self, query: str, k: int = 6) -> dict[str, Any]:
        k = max(1, min(int(k), 20))
        res = self.engine.recall(query, k=k, source=self.source, session=self.session)
        return {
            "recall_id": res["recall_id"], "confident": res["confident"],
            "best_similarity": res["best_similarity"],
            "results": [{
                "note": r["stem"], "path": r["path"], "title": r["title"], "score": r["score"],
                "section": r["heading"], "snippet": r["snippet"],
                **({"reached_via": f"{r['via']['kind']} link from {r['via']['seed_title']}"} if r.get("via") else {}),
            } for r in res["results"]],
        }

    def read_note(self, note: str) -> dict[str, Any]:
        row = self.brain.store.note_row(note)
        if row is None:
            raise KeyError(f"no note matches {note!r}")
        path = self.brain.cfg.root / row["path"]
        text = path.read_text(encoding="utf-8", errors="replace")
        truncated = len(text) > MAX_NOTE_CHARS
        if self.session:
            record_access(self.brain, self.session, int(row["id"]))
        return {"note": row["stem"], "path": row["path"], "title": row["title"], "truncated": truncated,
                "content": "<note_content>\n" + defuse(text[:MAX_NOTE_CHARS], "note_content") + "\n</note_content>"}

    def neighbors(self, note: str, limit: int = 12) -> dict[str, Any]:
        row = self.brain.store.note_row(note)
        if row is None:
            raise KeyError(f"no note matches {note!r}")
        g = self.brain.graph()
        titles = {r["id"]: (r["stem"], r["title"]) for r in self.brain.store.q("SELECT id,stem,title FROM notes")}
        best: dict[int, tuple[float, str, bool]] = {}
        for v, w, kind, fwd in g.neighbors(int(row["id"])):
            if w > best.get(v, (0.0, "", True))[0]:
                best[v] = (w, kind, fwd)
        items = sorted(best.items(), key=lambda kv: -kv[1][0])[: max(1, min(int(limit), 50))]
        return {"note": row["stem"], "neighbors": [{
            "note": titles[v][0], "title": titles[v][1], "kind": kind,
            "direction": "outgoing" if fwd else "backlink", "weight": round(w, 3),
        } for v, (w, kind, fwd) in items]}

    def suggest_links(self, note: str) -> dict[str, Any]:
        row = self.brain.store.note_row(note)
        if row is None:
            raise KeyError(f"no note matches {note!r}")
        pending = [p for p in P.listing(self.brain, "pending", "link", 500)
                   if row["path"] in (p["payload"]["src_path"], p["payload"]["dst_path"])]
        return {"note": row["stem"], "proposals": [{
            "id": p["id"], "from": p["payload"]["src_title"], "to": p["payload"]["dst_title"],
            "probability": p["payload"].get("probability", p["score"]), "why": p["payload"].get("why"),
            "method": p["method"],
        } for p in pending]}

    def propose_link(self, src: str, dst: str, why: str) -> dict[str, Any]:
        a, b = self.brain.store.note_row(src), self.brain.store.note_row(dst)
        if a is None or b is None:
            raise KeyError("both notes must exist")
        if a["id"] == b["id"]:
            raise ValueError("a note cannot link to itself")
        if P.is_protected(self.brain.cfg, a["path"]):
            raise PermissionError(f"{a['path']} is regenerated by another program; propose the link from {b['stem']} instead")
        payload = {"src_path": a["path"], "dst_path": b["path"], "src_title": a["title"], "dst_title": b["title"],
                   "why": _clean(why, 160), "proposed_by": self.source}
        created = P.upsert(self.brain, "link", P.link_key(a["path"], b["path"]), payload, 0.5, f"agent:{self.source}")
        return {"staged": created, "note": "staged for human review; nothing was written to the vault"
                if created else "a proposal for this pair already exists (possibly already decided)"}

    def propose_note(self, title: str, content: str, why: str) -> dict[str, Any]:
        """Stage a note — after it passes the authenticity gate. A draft with a
        high-severity default pattern is returned with the exact findings instead
        of being staged, so the agent revises before a person ever sees it."""
        title = _clean(title, 100)
        if not title:
            raise ValueError("title is required")
        report = self.critique(content)
        self.brain.store.metric("quality.agent_note.score", report["score"],
                                {"source": self.source, "blocking": report["blocking"]})
        if report["blocking"] or report["score"] >= 40:
            return {"staged": False, "needs_revision": True, "score": report["score"],
                    "verdict": report["verdict"], "findings": report["findings"],
                    "voice": report["voice"], "note": "revise and call propose_note again"}
        payload = {"title": title, "content": content[:20000], "why": _clean(why, 300), "proposed_by": self.source,
                   "quality": {"score": report["score"], "verdict": report["verdict"],
                               "voice_distance": report["voice"].get("distance")}}
        key = "note:" + re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
        created = P.upsert(self.brain, "note", key, payload, 0.5, f"agent:{self.source}")
        return {"staged": created, "inbox": self.brain.cfg.inbox_dir, "quality": payload["quality"],
                "note": "staged for human review; written to the inbox only if accepted"}

    def critique(self, text: str) -> dict[str, Any]:
        """Authenticity check against the vault's anti-slop rules and the author's own voice."""
        from .quality import critique, vault_baseline
        return critique(text, vault_baseline(self.brain))

    def feedback(self, recall_id: str, note: str, useful: bool) -> dict[str, Any]:
        return record_feedback(self.brain, recall_id, note, 1.0 if useful else 0.0, self.source)

    def status(self) -> dict[str, Any]:
        path = self.brain.cfg.state / "self_model.json"
        if not path.exists():
            return {"status": "no self-model yet; run `myelin sleep`"}
        m = json.loads(path.read_text(encoding="utf-8"))
        q = m["reliability"]["quiz"]
        return {
            "notes": m["identity"]["notes"], "edges": m["identity"]["edges"],
            "topics": [t["label"] for t in m["identity"]["topics"]][:10],
            "quiz_holdout": q.get("holdout"), "ablations": q.get("ablations"),
            "link_prediction": {k: m["reliability"]["link_prediction"].get(k) for k in ("status", "chosen", "scores")},
            "gaps": m["gaps"][:5], "pending_proposals": m["pending_proposals"],
            "health": {k: m["health"][k] for k in ("broken_links", "orphan_count")},
            "ledger": m["ledger"], "generated_at": m["generated_at"],
        }

    def resolve(self, ref: str) -> int | None:
        return resolve_note(self.brain, ref)


def defuse(text: str, tag: str) -> str:
    """Neutralise a closing tag inside wrapped data. A note that contains
    `</note_content>` must not be able to end the wrapper early and have the
    rest of its text read as if it came from outside the vault."""
    return re.sub(rf"<(\s*)/(\s*){re.escape(tag)}", r"<\1\\/\2" + tag, text, flags=re.IGNORECASE)


def _clean(text: str, limit: int) -> str:
    return " ".join(str(text or "").split())[:limit]


